#!/usr/bin/env python3
"""Packs weather overlay sheets (tools/saver/fx_<name>.*) into include/saver_fx.h.

Each sheet: 4x2 frames on a black background. Every pixel is reduced to an
intensity level 0..7 (0 = untouched) drawn on the device as a blend toward one
tint colour. Frames are RLE coded:
  0rrrrrrr  -> r+1 transparent pixels (1..128)
  1vvvrrrr  -> r+1 pixels of level v (1..7), r+1 = 1..16
Sheets much brighter on average than the rest (lightning) are "flash" frames,
shown only once per WX_FLASH_MS cycle.
"""
import glob, os
from PIL import Image

W, H = 160, 120
# name, scale (1 = 160x120, 2 = 80x60), black threshold, frame ms, gain (alpha per level, /32)
FX = [("fog", 2, 30, 300, 4), ("drizzle", 1, 50, 120, 5), ("rain", 1, 45, 100, 4),
      ("snow", 1, 50, 220, 4), ("storm", 1, 45, 100, 4)]
ROOT = os.path.dirname(os.path.abspath(__file__))


def find(name):
    for ext in ("png", "webp", "jpg", "jpeg"):
        p = os.path.join(ROOT, "saver", f"fx_{name}.{ext}")
        if os.path.exists(p):
            return p
    raise SystemExit(f"missing tools/saver/fx_{name}.*")


def frames(path, w, h):
    im = Image.open(path).convert("RGB")
    fw, fh = im.width / 4, im.height / 2
    inset = max(1, round(4 * fw / 500))
    out = []
    for r in range(2):
        for c in range(4):
            box = (round(c * fw) + inset, round(r * fh) + inset,
                   round((c + 1) * fw) - inset, round((r + 1) * fh) - inset)
            out.append(im.crop(box).resize((w, h), Image.BOX))
    return out


def pixels(im):
    get = getattr(im, "get_flattened_data", None) or im.getdata
    return list(get())


def levels(fr, thr):
    px = pixels(fr)
    return [0 if max(p) <= thr else min(7, 1 + (max(p) - thr) * 7 // (256 - thr)) for p in px]


def rle(lv):
    out, i, n = [], 0, len(lv)
    while i < n:
        v = lv[i]
        j = i
        lim = 128 if v == 0 else 16
        while j < n and lv[j] == v and j - i < lim:
            j += 1
        k = j - i
        out.append(k - 1 if v == 0 else 0x80 | v << 4 | (k - 1))
        i = j
    return out


def unrle(data, n):
    lv = []
    for b in data:
        lv += [0] * ((b & 0x7F) + 1) if b < 0x80 else [(b >> 4) & 7] * ((b & 15) + 1)
    assert len(lv) == n
    return lv


def tint(frs, thr):
    acc = [0, 0, 0]; cnt = 0
    for fr in frs:
        for p in pixels(fr):
            if max(p) > max(128, thr):
                acc = [a + q for a, q in zip(acc, p)]; cnt += 1
    if not cnt:
        return (255, 255, 255)
    avg = [a / cnt for a in acc]
    m = max(avg)
    return tuple(min(255, round(a * 255 / m)) for a in avg)


def main():
    lines = ["// Generated by tools/pack_fx.py — do not edit.", "#pragma once", "#include <stdint.h>", ""]
    table, total = [], 0
    for name, sc, thr, ms, gain in FX:
        w, h = W // sc, H // sc
        frs = frames(find(name), w, h)
        lvs = [levels(f, thr) for f in frs]
        means = [sum(l) / len(l) for l in lvs]
        base = sorted(means)[len(means) // 2]
        flash = [i for i, m in enumerate(means) if m > 2.0 * base + 0.3]
        normal = [i for i in range(8) if i not in flash]
        data, at = [], [0]
        for l in lvs:
            enc = rle(l)
            assert unrle(enc, w * h) == l
            data += enc; at.append(len(data))
        r, g, b = tint(frs, thr)
        c565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        seq = normal + flash
        lines.append(f"static const uint8_t FX_{name.upper()}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(x) for x in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint32_t FX_{name.upper()}_AT[9] = {{{','.join(map(str, at))}}};")
        table.append(f"  {{FX_{name.upper()}_DATA, FX_{name.upper()}_AT, {sc}, {ms}, {gain}, 0x{c565:04X}, "
                     f"{len(normal)}, {len(flash)}, {{{','.join(map(str, seq))}}}}},")
        total += len(data) + 36
        print(f"{name}: {len(data)} B, tint=({r},{g},{b}), flash={flash}")
    lines += ["",
              "struct SaverFxData {",
              "  const uint8_t *data;",
              "  const uint32_t *at;   // byte offset of each frame (9 entries)",
              "  uint8_t scale;        // 1 = 160x120, 2 = 80x60 shown 2x",
              "  uint16_t frame_ms;",
              "  uint8_t gain;         // blend per level, /32",
              "  uint16_t tint;        // RGB565",
              "  uint8_t n_normal, n_flash;",
              "  uint8_t seq[8];       // normal frames, then flash frames",
              "};",
              f"#define SAVER_FX_COUNT {len(FX)}  // index = WeatherFx - 1",
              "static const SaverFxData SAVER_FX[SAVER_FX_COUNT] = {"] + table + ["};", ""]
    open(os.path.join(ROOT, "..", "include", "saver_fx.h"), "w").write("\n".join(lines))
    print(f"total {total} B")


main()
