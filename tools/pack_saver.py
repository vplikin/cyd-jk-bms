#!/usr/bin/env python3
"""Pack the screensaver scenes: per scene a key frame + per-frame patches.

Scenes (order = SaverScene index in firmware), each a 4x2 sprite sheet:
  0 morning  tools/saver/morning.webp
  1 day      tools/saver/day.webp
  2 night    tools/saver/night.webp
  3 late     tools/saver/late.webp, optional (firmware falls back to night)
Any image format Pillow reads works (.webp/.png/.jpg).

Sheets are cut into 8 frames (separator lines trimmed), box-scaled to 160x120,
converted to RGB565. Lossy-source noise is removed by snapping each pixel that is
within TOL of the scene's key (per-pixel median of all frames) to the key value,
so patches only hold real animation.

Patch stream per frame (uint16): offset, count, count pixels ...; frame k uses
patch[at[k] .. at[k+1]). Spans closer than GAP pixels are merged.
Output: include/saver_frames.h
"""
import os

from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
W, H = 160, 120
N = W * H
TOL = 40   # sum of |dR|+|dG|+|dB| (8-bit) treated as compression noise
GAP = 3


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def unpack(c):
    r, g, b = c >> 11, (c >> 5) & 63, c & 31
    return (r << 3 | r >> 2, g << 2 | g >> 4, b << 3 | b >> 2)


def sheet_frames(path, cols=4, rows=2, inset=4):
    im = Image.open(path).convert("RGB")
    fw, fh = im.width / cols, im.height / rows
    out = []
    for r in range(rows):
        for c in range(cols):
            box = (round(c * fw) + inset, round(r * fh) + inset,
                   round((c + 1) * fw) - inset, round((r + 1) * fh) - inset)
            fr = im.crop(box).resize((W, H), Image.BOX)
            b = fr.tobytes()
            out.append([rgb565(b[i], b[i + 1], b[i + 2]) for i in range(0, len(b), 3)])
    return out


def denoise(frames):
    rgb = [[unpack(c) for c in f] for f in frames]
    key = []
    for i in range(N):
        col = sorted(range(len(frames)), key=lambda k: sum(rgb[k][i]))
        key.append(frames[col[len(col) // 2]][i])
    krgb = [unpack(c) for c in key]
    out = []
    for f, fr in zip(frames, rgb):
        out.append([key[i] if sum(abs(a - b) for a, b in zip(fr[i], krgb[i])) <= TOL else f[i]
                    for i in range(N)])
    return key, out


def pack(key, frames):
    patch, at = [], [0]
    for fr in frames:
        i = 0
        while i < N:
            if fr[i] == key[i]:
                i += 1
                continue
            j = i
            while j < N:
                if fr[j] != key[j]:
                    j += 1
                    continue
                k = j
                while k < N and k - j < GAP and fr[k] == key[k]:
                    k += 1
                if k < N and k - j < GAP and fr[k] != key[k]:
                    j = k
                else:
                    break
            patch += [i, j - i] + fr[i:j]
            i = j
        at.append(len(patch))
    for k, fr in enumerate(frames):  # self-check
        fb = key[:]
        p = at[k]
        while p < at[k + 1]:
            o, n = patch[p], patch[p + 1]
            fb[o:o + n] = patch[p + 2:p + 2 + n]
            p += 2 + n
        assert fb == fr, k
    return patch, at


def arr(v):
    return ",\n".join(",".join(f"0x{x:04X}" for x in v[i:i + 16]) for i in range(0, len(v), 16))


def find(name):
    for ext in (".webp", ".png", ".jpg", ".jpeg"):
        p = os.path.join(here, "saver", name + ext)
        if os.path.exists(p):
            return p
    return None


scenes = []
for name in ("morning", "day", "night", "late"):
    path = find(name)
    if path:
        key, frames = denoise(sheet_frames(path))
    elif name == "late":
        break
    else:
        raise SystemExit(f"missing tools/saver/{name}.*")
    scenes.append((name.upper(), key, frames))

out = os.path.join(here, "..", "include", "saver_frames.h")
total = 0
with open(out, "w") as f:
    f.write("#pragma once\n#include <stdint.h>\n")
    f.write("// Generated by tools/pack_saver.py. Do not edit.\n")
    f.write("#define SAVER_FRAMES 8\n")
    f.write(f"#define SAVER_SCENE_COUNT {len(scenes)}\n")
    f.write("struct SaverSceneData {\n  const uint16_t *key;\n  const uint32_t *at;\n  const uint16_t *patch;\n};\n")
    for name, key, frames in scenes:
        assert len(frames) == 8
        patch, at = pack(key, frames)
        size = (N + len(patch)) * 2
        total += size
        print(f"{name}: key={N * 2} B patch={len(patch) * 2} B")
        f.write(f"static const uint16_t SAVER_{name}_KEY[{N}] = {{\n{arr(key)}\n}};\n")
        f.write(f"static const uint32_t SAVER_{name}_AT[{len(at)}] = {{{','.join(map(str, at))}}};\n")
        f.write(f"static const uint16_t SAVER_{name}_PATCH[{max(len(patch), 1)}] = {{\n{arr(patch) or '0'}\n}};\n")
    f.write("static const SaverSceneData SAVER_SCENES[] = {\n")
    for name, _, _ in scenes:
        f.write(f"    {{SAVER_{name}_KEY, SAVER_{name}_AT, SAVER_{name}_PATCH}},\n")
    f.write("};\n")
print(f"total {total} B")
